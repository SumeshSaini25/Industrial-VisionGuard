
from pathlib import Path
import sys
import argparse
import json
import re

PROJECT_ROOT = Path(__file__).resolve().parents[2]

if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from rag.rag_assistant import ask_assistant


def get_inspection_finding(inspection_result):
    """
    Produce deterministic inspection facts.
    These statements are not generated by the LLM.
    """

    status = inspection_result["status"]
    score = float(inspection_result["anomaly_score"])

    if status == "DEFECT":
        interpretation = (
            "PatchCore flagged a visual anomaly under its "
            "learned anomaly-detection criteria. "
            "The specific defect type, root cause, severity, "
            "and engineering acceptability have not been established."
        )

    elif status == "GOOD":
        interpretation = (
            "PatchCore classified the image as GOOD under its "
            "learned anomaly-detection criteria. "
            "This does not establish compliance with approved "
            "engineering specifications."
        )

    else:
        raise ValueError(
            f"Unexpected PatchCore prediction: {status}"
        )

    return {
        "status": status,
        "anomaly_score": score,
        "interpretation": interpretation,
    }


def validate_generated_guidance(text):
    """
    Reject some known misleading language.
    This is a basic safeguard, not full factual verification.
    """

    if not text or not text.strip():
        raise ValueError("Qwen returned empty guidance.")

    prohibited_patterns = [
        r"\b\d+(?:\.\d+)?\s*%\s*(?:confidence|probability)\b",
        r"\b(?:confidence|probability)\s*(?:of|is|:)\s*\d+(?:\.\d+)?\s*%",
        r"\b(?:confirmed|definitely)\s+(?:scratch|bent|deformed|color defect)\b",
        r"\b(?:confirmed|definitely)\s+(?:acceptable|unacceptable)\b",
    ]

    for pattern in prohibited_patterns:
        if re.search(pattern, text, flags=re.IGNORECASE):
            raise ValueError(
                "Generated guidance contains an unsupported claim. "
                "Please regenerate the report."
            )

    return text.strip()


def generate_inspection_report(inspection_result):

    finding = get_inspection_finding(inspection_result)

    question = f"""
A PatchCore visual inspection has been completed.

MODEL OUTPUT:
Prediction: {finding['status']}
Raw anomaly score: {finding['anomaly_score']:.4f}

FIXED INTERPRETATION:
{finding['interpretation']}

Generate ONLY advisory quality-control guidance.

Include:
1. Recommended manual verification steps
2. General follow-up actions
3. Limitations of the available evidence

Rules:
- Do not repeat or rewrite the model prediction.
- Do not assign PASS, FAIL, or REVIEW decisions.
- Do not call the anomaly acceptable or unacceptable.
- Do not identify a specific defect type.
- Do not invent measurements or engineering standards.
- Do not convert the anomaly score to a percentage.
- Do not claim to have examined the image.
- Cite relevant retrieved document sources.
- If a retrieved passage discusses a specific defect type,
  do not assume that type was observed.

Keep the response concise and professional.
"""

    rag_result = ask_assistant(question)

    guidance = validate_generated_guidance(
        rag_result["answer"]
    )

    return {
        "inspection": inspection_result,
        "finding": finding,
        "report": guidance,
        "sources": rag_result["sources"],
    }


def main():

    parser = argparse.ArgumentParser(
        description="Generate a grounded quality-control report"
    )

    parser.add_argument(
        "--result",
        required=True,
        help="Path to a PatchCore result.json file",
    )

    args = parser.parse_args()

    with open(args.result, encoding="utf-8") as file:
        inspection_result = json.load(file)

    output = generate_inspection_report(
        inspection_result
    )

    finding = output["finding"]

    print("\n" + "=" * 60)
    print("INDUSTRIAL VISIONGUARD - QC REPORT")
    print("=" * 60)

    print("\nINSPECTION FINDING")
    print(f"Prediction: {finding['status']}")
    print(
        f"Raw anomaly score: "
        f"{finding['anomaly_score']:.4f}"
    )
    print(f"Interpretation: {finding['interpretation']}")

    print("\nAI-GENERATED ADVISORY GUIDANCE")
    print(output["report"])

    print("\nRETRIEVED REFERENCES")

    for index, source in enumerate(
        output["sources"],
        start=1,
    ):
        print(
            f"[{index}] {source['source']} "
            f"(distance: {source['distance']:.4f})"
        )


if __name__ == "__main__":
    main()
